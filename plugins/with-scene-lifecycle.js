const fs = require('fs');
const path = require('path');

const {
  IOSConfig,
  withAppDelegate,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject,
} = require('@expo/config-plugins');

/**
 * Adopts the UIKit scene-based life cycle on iOS.
 *
 * The iOS 27 SDK traps at launch in
 * `_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption` unless the
 * app declares `UIApplicationSceneManifest`, and Expo SDK 57's AppDelegate
 * template still builds the window itself. Without this the app dies with
 * `EXC_BREAKPOINT` on the splash screen, before any JS runs.
 *
 * This lives in a plugin rather than in the committed `ios/` tree because
 * `expo prebuild` regenerates those files from the template — twice already it
 * has silently removed the hand-written version and brought the crash back.
 */

const SCENE_DELEGATE_FILENAME = 'SceneDelegate.swift';

const SCENE_DELEGATE_SOURCE = `internal import Expo

// Generated by plugins/with-scene-lifecycle.js — edit the plugin, not this file.
//
// \`ExpoAppSceneDelegate\` creates the window from the connecting
// \`UIWindowScene\` and starts React Native into it; \`UIApplicationSceneManifest\`
// in Info.plist is what tells UIKit to use this class.
class SceneDelegate: ExpoAppSceneDelegate {}
`;

// What the template's AppDelegate does, and what it has to become. The window
// block is replaced rather than deleted: SceneDelegate starts React Native now,
// and leaving both in place would start it twice.
const TEMPLATE_WINDOW_BLOCK = `#if os(iOS) || os(tvOS)
    window = UIWindow(frame: UIScreen.main.bounds)
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions)
#endif`;

const SCENE_WINDOW_COMMENT = `// The window is created and React Native is started by \`SceneDelegate\`
    // (see Info.plist's \`UIApplicationSceneManifest\`), not here, since iOS 27
    // requires the scene-based life cycle.`;

const TEMPLATE_CLASS_DECL = 'class AppDelegate: ExpoAppDelegate {';
// SceneDelegate reaches the factory through this protocol, so the app delegate
// has to advertise it.
const SCENE_CLASS_DECL = 'class AppDelegate: ExpoAppDelegate, ExpoReactNativeFactoryProvider {';

/** Tell UIKit which class owns the window scene. */
const withSceneManifest = (config) =>
  withInfoPlist(config, (config) => {
    config.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return config;
  });

/** Write SceneDelegate.swift next to AppDelegate.swift. */
const withSceneDelegateFile = (config) =>
  withDangerousMod(config, [
    'ios',
    (config) => {
      const sourceRoot = IOSConfig.Paths.getSourceRoot(config.modRequest.projectRoot);
      fs.writeFileSync(path.join(sourceRoot, SCENE_DELEGATE_FILENAME), SCENE_DELEGATE_SOURCE);
      return config;
    },
  ]);

/** Compile it: a file on disk that no target builds would not help. */
const withSceneDelegateCompiled = (config) =>
  withXcodeProject(config, (config) => {
    const project = config.modResults;
    const groupName = path.basename(
      IOSConfig.Paths.getSourceRoot(config.modRequest.projectRoot)
    );
    const filepath = `${groupName}/${SCENE_DELEGATE_FILENAME}`;

    if (!project.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName, project });
    }
    return config;
  });

/** Hand the window over from AppDelegate to SceneDelegate. */
const withSceneAppDelegate = (config) =>
  withAppDelegate(config, (config) => {
    if (config.modResults.language !== 'swift') {
      throw new Error(
        `with-scene-lifecycle expects a Swift AppDelegate, found "${config.modResults.language}".`
      );
    }

    let contents = config.modResults.contents;

    if (contents.includes(TEMPLATE_WINDOW_BLOCK)) {
      contents = contents.replace(TEMPLATE_WINDOW_BLOCK, SCENE_WINDOW_COMMENT);
    } else if (!contents.includes(SCENE_WINDOW_COMMENT)) {
      // Fail loudly: an SDK upgrade that reshapes the template would otherwise
      // leave the window being built in both places, or in neither.
      throw new Error(
        'with-scene-lifecycle could not find the window block in AppDelegate.swift. ' +
          'The Expo template has changed — update TEMPLATE_WINDOW_BLOCK in this plugin.'
      );
    }

    if (contents.includes(TEMPLATE_CLASS_DECL)) {
      contents = contents.replace(TEMPLATE_CLASS_DECL, SCENE_CLASS_DECL);
    } else if (!contents.includes(SCENE_CLASS_DECL)) {
      throw new Error(
        'with-scene-lifecycle could not find the AppDelegate class declaration. ' +
          'The Expo template has changed — update TEMPLATE_CLASS_DECL in this plugin.'
      );
    }

    config.modResults.contents = contents;
    return config;
  });

module.exports = (config) =>
  withSceneAppDelegate(
    withSceneDelegateCompiled(withSceneDelegateFile(withSceneManifest(config)))
  );
